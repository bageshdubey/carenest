export type UiKey = keyof (typeof UI)["en"];

export function ui(lang: ChildLang, key: UiKey, vars: Record<string, string | number> = {}): string {
  return (UI[lang][key] as string).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function makeT(lang: ChildLang, base: Record<string, string | number> = {}) {
  return (key: UiKey, vars: Record<string, string | number> = {}) => ui(lang, key, { ...base, ...vars });
}

